import { readdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../../', import.meta.url);
const directory = new URL('backplanepb/console/v1/', root);
const profiles = {
  PlatformService: 'platform', CatalogService: 'catalog', SessionService: 'session', ConfigService: 'config',
  BindingService: 'binding', RuleService: 'rule', EventService: 'operations',
  WorkflowService: 'operations', ScheduleService: 'operations', CallService: 'operations',
  AuditService: 'audit', ObsService: 'observability', ErrorService: 'errors', WiringService: 'wiring',
};
const commands = new Set(('CreateSchedule UpdateSchedule DeleteSchedule PublishTestEvent RedriveDeadLetters PurgeDeadLetters StartWorkflow CancelRun TerminateRun SignalRun PauseSchedule UnpauseSchedule TriggerSchedule CallHook RunActivity TestBinding CancelBindingRun TestRule CancelRuleRun').split(' '));
const mutations = new Set(('SaveRevision Rollback SaveBinding RollbackBinding DeleteBinding SaveRule RollbackRule DeleteRule PauseRule ResumeRule RevokeSession RevokeOtherSessions').split(' '));
const markdown = [
  '# Console API method reference', '',
  'Generated by `web/scripts/api-reference.mjs` from every `backplane.console.v1` service.',
  'Run `make gen` after changing protos. [Transport, status families and working examples](api-client.md).',
  'All RPC paths start with `/backplane.console.v1.`. All calls use the console cookie.',
  'Each error family below is a conservative service-level set; common transport/auth statuses also apply.',
  'Structured validation, call failures and partial batch results must also be inspected on successful RPC responses.', '',
];
const examples = [
  '// Generated callable wrappers; request values come from the caller/form.',
  "import type * as API from '@backplane-labs/backplane-api';",
];
let count = 0;
for (const file of (await readdir(directory)).filter((name) => name.endsWith('.proto')).sort()) {
  const source = await readFile(new URL(file, directory), 'utf8');
  for (const service of source.matchAll(/^service (\w+) \{([\s\S]*?)^\}/gm)) {
    const name = service[1], profile = profiles[name];
    if (!profile) throw new Error(`Document an error family for ${name}`);
    markdown.push(`## ${name}`, '', `[Source and message fields](../backplanepb/console/v1/${file}). Error family: [${profile}](api-client.md#${profile}).`, '');
    for (const method of service[2].matchAll(/((?:[ \t]*\/\/[^\n]*\n)*)[ \t]*rpc (\w+)\((\w+)\) returns \((stream )?(\w+)\);/g)) {
      const [, comments, rpc, request, stream, response] = method;
      const js = rpc[0].toLowerCase() + rpc.slice(1);
      const description = comments.replace(/^[ \t]*\/\/ ?/gm, '').trim().replace(/\n\s*/g, ' ');
      const mode = stream ? (rpc === 'WatchAudit' ? 'cursor deltas' : 'replacement snapshots') : 'unary';
      const policy = commands.has(rpc) ? 'External command: durable intent/result; never automatically replay. Additional audit statuses: `Unavailable` before dispatch, `Aborted` if result persistence fails.'
        : mutations.has(rpc) ? 'Database mutation: never automatically replay after an ambiguous failure.'
          : stream ? 'Long-lived read; recovery follows its stream semantics.' : 'Read/validation: safe to retry after a transient failure.';
      markdown.push(`### ${rpc}`, '', description || `${rpc} is a ${mode} operation.`, '',
        `- Path: \`/backplane.console.v1.${name}/${rpc}\`.`,
        `- Input: \`${request}\`; output: \`${response}\`; mode: ${mode}.`,
        `- Errors: [${profile}](api-client.md#${profile}) + [common](api-client.md#common).`,
        `- ${policy}`, '', '```ts',
        `// client: ${name}Client; request: ${request}; signal: AbortSignal`,
        ...(stream ? [`for await (const response of client.${js}(request, { signal })) {`, '  console.log(response);', '}']
          : [`const response = await client.${js}(request, { signal });`]), '```', '');
      examples.push(`export function ${name}_${rpc}(client: API.${name}Client, request: API.${request}, signal: AbortSignal) {`,
        `  return client.${js}(request, { signal });`, '}');
      count++;
    }
  }
}
markdown.splice(6, 0, `Inventory: **${count} RPCs in ${Object.keys(profiles).length} services**.`);
await writeFile(new URL('docs/api-reference.md', root), markdown.join('\n'));
await writeFile(new URL('web/tests/api-examples.generated.ts', root), examples.join('\n') + '\n');
console.log(`Documented and generated typechecked call examples for ${count} console RPCs`);
